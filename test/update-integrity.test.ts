import { createHash } from 'node:crypto'
import { describe, expect, it } from 'vitest'
import {
  assertExpectedReleaseTag,
  assertReleaseTag,
  isValidReleaseTag,
  parseSha256Digest,
  parseSha256Sums,
  verifyAsset,
  verifyDigest
} from '@main/core/update-integrity'

const PAYLOAD = Buffer.from('skipnet-integrity-fixture')
const HEX = createHash('sha256').update(PAYLOAD).digest('hex')
const DIGEST = `sha256:${HEX}`

describe('verifyDigest', () => {
  it('accepts a lowercase sha256 digest', () => {
    expect(() => verifyDigest(PAYLOAD, DIGEST, 'файла')).not.toThrow()
  })

  it('accepts an uppercase sha256 digest (case-insensitive)', () => {
    expect(() => verifyDigest(PAYLOAD, DIGEST.toUpperCase(), 'файла')).not.toThrow()
  })

  it('throws when the digest is missing', () => {
    expect(() => verifyDigest(PAYLOAD, undefined, 'файла')).toThrow(/Отсутствует контрольная сумма/)
    expect(() => verifyDigest(PAYLOAD, null, 'файла')).toThrow(/Отсутствует контрольная сумма/)
    expect(() => verifyDigest(PAYLOAD, '   ', 'файла')).toThrow(/Отсутствует контрольная сумма/)
  })

  it.each([
    ['md5', `md5:${HEX}`],
    ['sha512', `sha512:${HEX}`],
    ['short hex', 'sha256:abc'],
    ['63 hex chars', `sha256:${HEX.slice(1)}`],
    ['non-hex', `sha256:${'z'.repeat(64)}`]
  ])('throws on a malformed %s digest', (_name, digest) => {
    expect(() => verifyDigest(PAYLOAD, digest, 'файла')).toThrow(/Некорректная контрольная сумма/)
  })

  it('throws when the bytes do not match', () => {
    const other = createHash('sha256').update('tampered').digest('hex')
    expect(() => verifyDigest(PAYLOAD, `sha256:${other}`, 'файла')).toThrow(/не совпадает/)
  })
})

describe('verifyAsset', () => {
  it('throws when GitHub did not report a size', () => {
    expect(() =>
      verifyAsset(PAYLOAD, { digest: DIGEST, size: undefined, label: 'установщика' })
    ).toThrow(/Не удалось определить размер/)
  })

  it('throws on a size mismatch', () => {
    expect(() =>
      verifyAsset(PAYLOAD, { digest: DIGEST, size: PAYLOAD.length + 1, label: 'установщика' })
    ).toThrow(/Размер установщика не совпадает/)
  })

  it('throws when the file is smaller than minBytes', () => {
    expect(() =>
      verifyAsset(PAYLOAD, {
        digest: DIGEST,
        size: PAYLOAD.length,
        minBytes: 5 * 1024 * 1024,
        label: 'установщика'
      })
    ).toThrow(/слишком маленький/)
  })

  it('throws when the digest is missing even if the size matches', () => {
    expect(() =>
      verifyAsset(PAYLOAD, { digest: null, size: PAYLOAD.length, label: 'установщика' })
    ).toThrow(/Отсутствует контрольная сумма/)
  })

  it('passes with a valid digest, size and floor', () => {
    expect(() =>
      verifyAsset(PAYLOAD, {
        digest: DIGEST.toUpperCase(),
        size: PAYLOAD.length,
        minBytes: 10,
        label: 'установщика'
      })
    ).not.toThrow()
  })

  it('rejects an empty buffer', () => {
    expect(() =>
      verifyAsset(Buffer.alloc(0), { digest: DIGEST, size: 1, label: 'файла' })
    ).toThrow(/пуст/)
  })
})

describe('parseSha256Digest', () => {
  it('normalises valid digests and rejects everything else', () => {
    expect(parseSha256Digest(`SHA256:${HEX.toUpperCase()}`)).toBe(DIGEST)
    expect(parseSha256Digest(`md5:${HEX}`)).toBeNull()
    expect(parseSha256Digest('')).toBeNull()
    expect(parseSha256Digest(null)).toBeNull()
  })
})

describe('parseSha256Sums', () => {
  const sums = [
    '# generated by archive-release.mjs',
    '',
    `${'a'.repeat(64)}  SkipNet_x64.exe`,
    `${HEX}  *SkipNet_x64-portable.7z`,
    '   ',
    `${'b'.repeat(64)}  ./nested/zapret-discord-youtube-1.10.4.zip`
  ].join('\r\n')

  it('parses the line for the requested asset', () => {
    expect(parseSha256Sums(sums, 'SkipNet_x64.exe')).toBe(`sha256:${'a'.repeat(64)}`)
  })

  it('tolerates the binary-mode marker and a leading ./', () => {
    expect(parseSha256Sums(sums, 'SkipNet_x64-portable.7z')).toBe(DIGEST)
    expect(parseSha256Sums(sums, 'zapret-discord-youtube-1.10.4.zip')).toBe(
      `sha256:${'b'.repeat(64)}`
    )
  })

  it('ignores comments, blanks and unknown assets', () => {
    expect(parseSha256Sums('', 'SkipNet_x64.exe')).toBeNull()
    expect(parseSha256Sums(sums, 'missing.exe')).toBeNull()
    expect(parseSha256Sums(sums, '')).toBeNull()
  })
})

describe('release tag gate', () => {
  it('accepts v-prefixed and bare semver tags', () => {
    expect(isValidReleaseTag('v1.5.0')).toBe(true)
    expect(isValidReleaseTag('1.5.0')).toBe(true)
    expect(assertReleaseTag(' v1.5.0 ')).toBe('v1.5.0')
  })

  it.each(['latest', 'v1.5', 'v1.5.0-beta', '../v1.5.0', 'v1.5.0/../../x'])(
    'rejects %s',
    (tag) => {
      expect(isValidReleaseTag(tag)).toBe(false)
      expect(() => assertReleaseTag(tag)).toThrow(/Некорректный тег/)
    }
  )

  it('requires the tag to match the last checked release', () => {
    expect(assertExpectedReleaseTag('v1.5.0', 'v1.5.0')).toBe('v1.5.0')
    expect(() => assertExpectedReleaseTag('v1.4.0', 'v1.5.0')).toThrow(
      /не совпадает с последней проверенной/
    )
    expect(() => assertExpectedReleaseTag('v1.5.0', undefined)).toThrow(
      /не совпадает с последней проверенной/
    )
  })
})
