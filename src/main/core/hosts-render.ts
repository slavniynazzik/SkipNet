/**
 * Pure rendering/parsing helpers for the hosts editor.
 *
 * Keeping this module free of Electron/FS imports makes the block format easy
 * to reason about and test: `renderManagedBlock` produces the text, while
 * `buildHostsContent` preserves everything outside it.
 */

import { createHash } from 'node:crypto'
import { isIP } from 'node:net'

export const EDITOR_BLOCK_START = '# --- SkipNet hosts editor BEGIN ---'
export const EDITOR_BLOCK_END = '# --- SkipNet hosts editor END ---'
export const LEGACY_SKIPNET_START = '# --- SkipNet (Zapret) hosts BEGIN ---'
export const LEGACY_SKIPNET_END = '# --- SkipNet (Zapret) hosts END ---'
export const ADOBE_BLOCK_START = '# --- SkipNet Adobe activation block BEGIN ---'
export const ADOBE_BLOCK_END = '# --- SkipNet Adobe activation block END ---'

const ZAPRETGUI_START_RE = /^#\s*>>>\s*zapretgui:hosts managed begin\s*>>>\s*$/i
const ZAPRETGUI_END_RE = /^#\s*<<<\s*zapretgui:hosts managed end\s*<<<\s*$/i

const LEGACY_ORPHAN_LINES = new Set([
  '# adobe activation block',
  '# generated by zapret-wingui',
  '# --- telegram proxy (auto-managed by zapret 2 gui) ---'
])

export interface ParsedHostsPair {
  ip: string
  hostname: string
}

export interface RenderedHostsBlock {
  content: string
  services: number
  lines: number
  warnings: string[]
}

function parsePair(line: string): { ip: string; hostnames: string[] } | null {
  const trimmed = line.trim()
  if (!trimmed || trimmed.startsWith('#')) return null
  const parts = trimmed.split(/\s+/)
  if (parts.length < 2) return null
  const ip = parts[0]
  if (!isIP(ip)) return null
  return { ip, hostnames: parts.slice(1).map((h) => h.toLowerCase()) }
}

function normalizeSelection(
  service: HostsService,
  state: HostsState
): string | null {
  const value = state.selection[service.id]
  if (!value || value === 'off') return null
  if (service.kind === 'hosts') return value === 'hosts' ? 'hosts' : null
  if (value === 'hosts') return state.defaultDnsProfile || null
  return value
}

/**
 * Render all enabled services into the managed block. Duplicate
 * `(ip, hostname)` pairs are collapsed; a hostname can legitimately appear
 * under several services, but writing the same pair twice adds no value.
 */
export function renderManagedBlock(catalog: HostsCatalog, state: HostsState): RenderedHostsBlock {
  const seen = new Set<string>()
  const lines: string[] = []
  const warnings: string[] = []
  let services = 0
  let count = 0

  for (const service of catalog.services) {
    const selection = normalizeSelection(service, state)
    if (!selection) continue

    const serviceLines: string[] = []
    if (service.kind === 'hosts') {
      for (const entry of service.entries ?? []) {
        for (const ip of entry.ips) {
          const key = `${ip.toLowerCase()} ${entry.hostname}`
          if (seen.has(key)) continue
          seen.add(key)
          serviceLines.push(`${ip} ${entry.hostname}`)
        }
      }
    } else {
      for (const domain of service.domains ?? []) {
        const ips = domain.answers[selection]
        if (!ips || ips.length === 0) {
          warnings.push(`${service.name}: нет адресов для профиля ${selection}`)
          continue
        }
        for (const ip of ips) {
          const key = `${ip.toLowerCase()} ${domain.hostname}`
          if (seen.has(key)) continue
          seen.add(key)
          serviceLines.push(`${ip} ${domain.hostname}`)
        }
      }
    }

    if (serviceLines.length === 0) continue
    services++
    count += serviceLines.length
    lines.push(`# >>> SkipNet service: ${service.id}`)
    lines.push(...serviceLines)
    lines.push(`# <<< SkipNet service: ${service.id}`)
  }

  const content =
    lines.length === 0
      ? ''
      : `${EDITOR_BLOCK_START}\r\n${lines.join('\r\n')}\r\n${EDITOR_BLOCK_END}`

  return { content, services, lines: count, warnings }
}

export function renderAdobeBlock(hosts: string[]): string {
  if (hosts.length === 0) return ''
  const lines = hosts.map((hostname) => `127.0.0.1 ${hostname}`)
  return `${ADOBE_BLOCK_START}\r\n${lines.join('\r\n')}\r\n${ADOBE_BLOCK_END}`
}

function isAdobeEntry(line: string, adobeHosts: Set<string>): boolean {
  const parsed = parsePair(line)
  if (!parsed || parsed.ip !== '127.0.0.1') return false
  return parsed.hostnames.some((hostname) => adobeHosts.has(hostname))
}

/**
 * Remove every block SkipNet owns or supersedes, but leave unrelated lines
 * (other apps, localhost entries, the legacy SkipNet Telegram block) intact.
 */
export function stripManagedBlocks(content: string, adobeHosts: Set<string>): string {
  const kept: string[] = []
  let inZapretGui = false
  let inLegacySkipNet = false
  let inEditor = false
  let inAdobeEditor = false

  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim()

    if (ZAPRETGUI_START_RE.test(trimmed)) {
      inZapretGui = true
      continue
    }
    if (inZapretGui) {
      if (ZAPRETGUI_END_RE.test(trimmed)) inZapretGui = false
      continue
    }

    if (trimmed === LEGACY_SKIPNET_START) {
      inLegacySkipNet = true
      continue
    }
    if (inLegacySkipNet) {
      if (trimmed === LEGACY_SKIPNET_END) inLegacySkipNet = false
      continue
    }

    if (trimmed === EDITOR_BLOCK_START) {
      inEditor = true
      continue
    }
    if (inEditor) {
      if (trimmed === EDITOR_BLOCK_END) inEditor = false
      continue
    }

    if (trimmed === ADOBE_BLOCK_START) {
      inAdobeEditor = true
      continue
    }
    if (inAdobeEditor) {
      if (trimmed === ADOBE_BLOCK_END) inAdobeEditor = false
      continue
    }

    if (isAdobeEntry(line, adobeHosts)) continue
    if (LEGACY_ORPHAN_LINES.has(trimmed.toLowerCase())) continue

    // Collapse runs of blank lines but keep the file readable.
    if (trimmed === '' && kept.length > 0 && kept[kept.length - 1].trim() === '') continue
    kept.push(line)
  }

  while (kept.length > 0 && kept[0].trim() === '') kept.shift()
  while (kept.length > 0 && kept[kept.length - 1].trim() === '') kept.pop()
  return kept.join('\r\n')
}

export function buildHostsContent(
  original: string,
  managed: RenderedHostsBlock,
  adobeBlock: string,
  adobeEnabled: boolean,
  adobeHosts: Set<string>
): string {
  const base = stripManagedBlocks(original, adobeHosts)
  const parts: string[] = []
  if (base.trim()) parts.push(base.trimEnd())
  if (managed.content) parts.push(managed.content)
  if (adobeEnabled && adobeBlock) parts.push(adobeBlock)
  if (parts.length === 0) return ''
  return `${parts.join('\r\n\r\n')}\r\n`
}

export function hashHostsContent(content: string): string {
  return createHash('sha256').update(Buffer.from(content, 'latin1')).digest('hex')
}

export function countEditorBlockLines(content: string): number {
  let inBlock = false
  let count = 0
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (trimmed === EDITOR_BLOCK_START) {
      inBlock = true
      continue
    }
    if (trimmed === EDITOR_BLOCK_END) {
      inBlock = false
      continue
    }
    if (inBlock && trimmed !== '' && !trimmed.startsWith('#')) count++
  }
  return count
}

export function detectLegacyBlocks(
  content: string,
  adobeHosts: Set<string>
): HostsLegacyBlocks {
  let zapretGui = false
  let skipNet = false
  let adobe = false
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (ZAPRETGUI_START_RE.test(trimmed)) zapretGui = true
    if (trimmed === LEGACY_SKIPNET_START) skipNet = true
    if (trimmed === ADOBE_BLOCK_START) adobe = true
    if (!adobe && isAdobeEntry(line, adobeHosts)) adobe = true
  }
  return { zapretGui, skipNet, adobe }
}

export function parseLegacyZapretGui(content: string): ParsedHostsPair[] {
  const pairs: ParsedHostsPair[] = []
  let inBlock = false
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (ZAPRETGUI_START_RE.test(trimmed)) {
      inBlock = true
      continue
    }
    if (inBlock && ZAPRETGUI_END_RE.test(trimmed)) break
    if (!inBlock) continue
    const parsed = parsePair(line)
    if (!parsed) continue
    for (const hostname of parsed.hostnames) pairs.push({ ip: parsed.ip, hostname })
  }
  return pairs
}

export function parseLegacySkipNet(content: string): ParsedHostsPair[] {
  const pairs: ParsedHostsPair[] = []
  let inBlock = false
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim()
    if (trimmed === LEGACY_SKIPNET_START) {
      inBlock = true
      continue
    }
    if (inBlock && trimmed === LEGACY_SKIPNET_END) break
    if (!inBlock) continue
    const parsed = parsePair(line)
    if (!parsed) continue
    for (const hostname of parsed.hostnames) pairs.push({ ip: parsed.ip, hostname })
  }
  return pairs
}

export function parseAdobeEntries(content: string, adobeHosts: Set<string>): ParsedHostsPair[] {
  const pairs: ParsedHostsPair[] = []
  for (const line of content.split(/\r?\n/)) {
    const parsed = parsePair(line)
    if (!parsed || parsed.ip !== '127.0.0.1') continue
    for (const hostname of parsed.hostnames) {
      if (adobeHosts.has(hostname)) pairs.push({ ip: parsed.ip, hostname })
    }
  }
  return pairs
}

/**
 * Map the entries of a ZapretGUI block back to catalog services.
 * Hosts services match by their pinned IPs; DNS services match by the profile
 * whose pre-computed answers contain the address.
 */
export function importLegacySelection(
  catalog: HostsCatalog,
  pairs: ParsedHostsPair[],
  defaultProfile: string
): Record<string, HostsSelection> {
  const hostsIndex = new Map<string, Array<{ serviceId: string; ips: Set<string> }>>()
  const dnsIndex = new Map<string, Array<{ serviceId: string; answers: Record<string, string[]> }>>()

  for (const service of catalog.services) {
    if (service.kind === 'hosts') {
      for (const entry of service.entries ?? []) {
        const list = hostsIndex.get(entry.hostname) ?? []
        list.push({ serviceId: service.id, ips: new Set(entry.ips.map((ip) => ip.toLowerCase())) })
        hostsIndex.set(entry.hostname, list)
      }
    } else {
      for (const domain of service.domains ?? []) {
        const list = dnsIndex.get(domain.hostname) ?? []
        list.push({ serviceId: service.id, answers: domain.answers })
        dnsIndex.set(domain.hostname, list)
      }
    }
  }

  const hostsMatched = new Set<string>()
  const dnsCounts = new Map<string, Map<string, number>>()

  for (const pair of pairs) {
    const ip = pair.ip.toLowerCase()
    const hostname = pair.hostname.toLowerCase()

    for (const candidate of hostsIndex.get(hostname) ?? []) {
      if (candidate.ips.has(ip)) hostsMatched.add(candidate.serviceId)
    }
    for (const candidate of dnsIndex.get(hostname) ?? []) {
      for (const [profileId, ips] of Object.entries(candidate.answers)) {
        if (!ips.some((value) => value.toLowerCase() === ip)) continue
        const perService = dnsCounts.get(candidate.serviceId) ?? new Map<string, number>()
        perService.set(profileId, (perService.get(profileId) ?? 0) + 1)
        dnsCounts.set(candidate.serviceId, perService)
      }
    }
  }

  const selection: Record<string, HostsSelection> = {}
  for (const serviceId of hostsMatched) selection[serviceId] = 'hosts'
  for (const [serviceId, counts] of dnsCounts) {
    let bestProfile = defaultProfile
    let bestCount = -1
    for (const [profileId, count] of counts) {
      if (count > bestCount) {
        bestCount = count
        bestProfile = profileId
      }
    }
    if (bestProfile) selection[serviceId] = bestProfile
  }
  return selection
}
